// Regenerates src/types/kpax-openapi.generated.ts from the KPAX OpenAPI spec.
//
// The spec is KPAX's documentation and is NOT committed to this repo. Download it
// from your own instance while logged in:
//   https://<instance>.kpax.cloud/api/docs?api-docs.json  ->  openapi/kpax-openapi.json (repo root)
// then run (from node/): npm run generate:types
//
// Descriptions and examples from the spec are stripped from the output, so the
// committed file contains type structure only.
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const spec = process.argv[2] || path.join(root, '../openapi/kpax-openapi.json');
const out = path.join(root, 'src/types/kpax-openapi.generated.ts');

if (!fs.existsSync(spec)) {
  console.error(`KPAX spec not found at ${spec}.\nDownload it from https://<instance>.kpax.cloud/api/docs?api-docs.json (logged in) and save it there.`);
  process.exit(1);
}

execFileSync(path.join(root, 'node_modules/.bin/openapi-typescript'), [spec, '-o', out], {
  stdio: 'inherit',
});

let src = fs.readFileSync(out, 'utf8');
// Drop every JSDoc block (descriptions, examples, formats) and the blank lines it leaves.
src = src.replace(/^[ \t]*\/\*\*[\s\S]*?\*\/[ \t]*\r?\n/gm, '');
const header =
  '/* eslint-disable */\n' +
  '// Generated by scripts/generate-types.js (openapi-typescript) from the KPAX API v1\n' +
  '// OpenAPI spec. Type structure only; descriptions are stripped. Do not edit.\n';
fs.writeFileSync(out, header + src);
console.log(`Wrote ${path.relative(root, out)}`);
